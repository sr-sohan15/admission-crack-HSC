// Row format: [question, correctAnswer, [wrong1, wrong2, wrong3], hack]
//
// IMPORTANT:
// - `appearances` is intentionally EMPTY. Fill it ONLY from real past papers
//   (e.g. { exam: "GST", year: "21-22" }). Never guess a year tag.
// - `paperVerified: false` = answer is a standard textbook fact, but its
//   appearance in past papers is NOT yet confirmed. Flip to true after you
//   match it with a real question bank.
// - Correct option position is rotated automatically (answerIndex).

const build = (subject, topic, rows) =>
  rows.map(([question, correct, wrongs, hack], i) => {
    const pos = i % 4;
    const options = [...wrongs];
    options.splice(pos, 0, correct);
    return {
      id: `${subject}-${topic}-${i + 1}`,
      subject,
      topic,
      question,
      options,
      answer: correct,
      answerIndex: pos,
      hack,
      appearances: [],
      paperVerified: false,
    };
  });

